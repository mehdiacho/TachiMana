package tachimana.extension.loader

import net.dongliu.apk.parser.ApkFile
import org.w3c.dom.Element
import org.w3c.dom.Node
import java.io.File
import javax.xml.parsers.DocumentBuilderFactory

/**
 * The subset of an extension APK's manifest TachiMana needs to load it: package identity, version,
 * and the `application`-level `<meta-data>` entries that name the source class(es).
 */
data class ApkMetadata(
    val packageName: String,
    val versionName: String,
    val versionCode: Long,
    val label: String?,
    val metaData: Map<String, String>,
) {
    /** `tachiyomi.extension.class` — a `;`-separated list of Source / SourceFactory class names. */
    fun sourceClasses(): List<String> {
        val raw = metaData[PackageTools.METADATA_SOURCE_CLASS]?.trim().orEmpty()
        if (raw.isEmpty()) return emptyList()
        return raw.split(";").map { it.trim() }.filter { it.isNotEmpty() }.map { cls ->
            if (cls.startsWith(".")) packageName + cls else cls
        }
    }

    val isNsfw: Boolean get() = metaData[PackageTools.METADATA_NSFW]?.trim() == "1"

    val extensionName: String
        get() = metaData[PackageTools.METADATA_NAME]
            ?: label?.substringAfter("Tachiyomi: ")
            ?: packageName

    val extensionLibVersion: String
        get() = metaData[PackageTools.METADATA_EXTENSION_LIB]
            ?.let { decodeManifestValue(it) }
            ?.takeUnless { it == "0" || it == "0.0" }
            ?: versionName.substringBeforeLast('.')

    companion object {
        /**
         * AAPT stores non-string `android:value`s as typed binary values, which apk-parser
         * renders as `{type:data}` — e.g. `android:value="1.4"` becomes `{4:1068708659}`
         * (type 4 = float, data = the IEEE-754 bits). Decode the types extensions use.
         */
        private fun decodeManifestValue(raw: String): String {
            val m = Regex("""\{(\d+):(-?\d+)}""").matchEntire(raw.trim()) ?: return raw
            val (type, data) = m.destructured
            return when (type.toInt()) {
                4 -> Float.fromBits(data.toInt()).toString() // TYPE_FLOAT
                16 -> data // TYPE_INT_DEC
                else -> raw
            }
        }

        /**
         * Read the metadata out of a published extension **jar**. Those ship the manifest as
         * plain-text `AndroidManifest.xml` (generated by Keiyoushi's Gradle plugin), so there is
         * no AAPT binary encoding to decode — and no apk-parser in the path.
         */
        fun readJar(jar: File): ApkMetadata {
            val xml = java.util.zip.ZipFile(jar).use { zip ->
                val entry = zip.getEntry("AndroidManifest.xml")
                    ?: error("${jar.name} has no AndroidManifest.xml — not an extension jar")
                zip.getInputStream(entry).use { it.readBytes() }
            }
            require(xml.isNotEmpty() && xml[0] == '<'.code.toByte()) {
                "${jar.name} has a binary AndroidManifest.xml; expected the plain-text one jars ship"
            }
            val doc = DocumentBuilderFactory.newInstance().newDocumentBuilder()
                .parse(xml.inputStream())
            val manifest = doc.documentElement
            val app = doc.getElementsByTagName("application").item(0)
            return ApkMetadata(
                packageName = manifest.getAttribute("package"),
                versionName = manifest.getAttribute("android:versionName").ifBlank { "0" },
                versionCode = manifest.getAttribute("android:versionCode").toLongOrNull() ?: 0L,
                label = (app as? Element)?.getAttribute("android:label")?.takeIf { it.isNotBlank() },
                metaData = readMetaData(app),
            )
        }

        private fun readMetaData(appTag: Node?): Map<String, String> {
            val meta = mutableMapOf<String, String>()
            appTag?.childNodes?.let { children ->
                for (i in 0 until children.length) {
                    val node = children.item(i)
                    if (node.nodeType != Node.ELEMENT_NODE) continue
                    val el = node as Element
                    if (el.tagName != "meta-data") continue
                    val name = el.attributes.getNamedItem("android:name")?.nodeValue ?: continue
                    val value = el.attributes.getNamedItem("android:value")?.nodeValue ?: continue
                    meta[name] = value
                }
            }
            return meta
        }

        fun read(apk: File): ApkMetadata =
            ApkFile(apk).use { parsed ->
                val apkMeta = parsed.apkMeta
                val meta = mutableMapOf<String, String>()

                val dBuilder = DocumentBuilderFactory.newInstance().newDocumentBuilder()
                val doc = parsed.manifestXml.byteInputStream().use { dBuilder.parse(it) }
                meta += readMetaData(doc.getElementsByTagName("application").item(0))

                ApkMetadata(
                    packageName = apkMeta.packageName,
                    versionName = apkMeta.versionName ?: "0",
                    versionCode = apkMeta.versionCode ?: 0L,
                    label = apkMeta.label,
                    metaData = meta,
                )
            }
    }
}
